"""Generate stub episodes, the component map (episodes/all.ts) and durations.ts
for the batch range 206-250. Re-run after each wave: durations.ts picks up any
timeline_NNN.json that exists, else falls back to 3600 frames."""

import json
import os

BASE = os.path.join(os.path.dirname(__file__), '..', 'src')
EPS = range(206, 251)

STUB = """import React from 'react';
import {AbsoluteFill} from 'remotion';
import {C, FONT_HEAD} from '../lib/style';

export const E@N@ = ({data}: {data?: any}) => (
  <AbsoluteFill style={{background: C.bg0, justifyContent: 'center', alignItems: 'center'}}>
    <div style={{color: C.text, fontFamily: FONT_HEAD, fontSize: 80}}>@N@ 占位</div>
  </AbsoluteFill>
);
"""

for n in EPS:
    p = os.path.join(BASE, 'episodes', 'E%d.tsx' % n)
    if not os.path.exists(p):
        open(p, 'w', encoding='utf-8').write(STUB.replace('@N@', str(n)))

all_ts = ['// generated by tools/gen_batch.py'] + [
    'import {E%d} from \'./E%d\';' % (n, n) for n in EPS]
all_ts.append('export const COMPS: Record<number, any> = {%s};' % ', '.join(
    '%d: E%d' % (n, n) for n in EPS))
open(os.path.join(BASE, 'episodes', 'all.ts'), 'w', encoding='utf-8').write('\n'.join(all_ts) + '\n')

durs = {}
for n in EPS:
    tp = os.path.join(BASE, 'timeline_%d.json' % n)
    if os.path.exists(tp):
        durs[n] = int(-(-json.load(open(tp, encoding='utf-8'))['totalSec'] * 30 // 1))
    else:
        durs[n] = 3600
open(os.path.join(BASE, 'durations.ts'), 'w', encoding='utf-8').write(
    '// generated by tools/gen_batch.py\nexport const DURATIONS: Record<number, number> = %s;\n'
    % json.dumps(durs))
print('durations:', durs)
